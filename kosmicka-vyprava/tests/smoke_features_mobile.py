import asyncio, os, sys, subprocess, time
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
from playwright.async_api import async_playwright
srv = subprocess.Popen([sys.executable,'-m','http.server','8765','--directory',ROOT],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
time.sleep(1)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'])
        pg = await b.new_page(viewport={'width':1440,'height':860})
        logs=[]
        pg.on('console', lambda m: logs.append(m.type+': '+m.text) if m.type=='error' else None)
        pg.on('pageerror', lambda e: logs.append('PAGEERR: '+str(e)))
        await pg.goto('http://localhost:8765/index.html')
        await pg.wait_for_timeout(5000)
        await pg.click('[data-start="kid"]')
        await pg.click('#dock [data-go="uranus"]')
        await pg.wait_for_timeout(4500)
        print(await pg.evaluate("(()=>{const e=document.elementFromPoint(1250,730);return e.tagName+'#'+e.id+'.'+e.className})()"))
        await pg.click('[data-tab="pass"]')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='u1_uranus_pass.png')
        await pg.click('[data-tab="lab"]')
        await pg.fill('#lab-kg','32')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='u2_lab.png')
        await pg.click('[data-act="cmp-open"]')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='u3_cmp.png')
        await pg.select_option('#cmp-b2','saturn'); await pg.select_option('#cmp-a2','sun')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='u3b_cmp.png')
        await pg.click('[data-act="cmp-close"]')
        await pg.click('[data-act="panel-close"]')
        await pg.click('[data-act="home"]'); await pg.click('[data-act="scale1"]')
        await pg.wait_for_timeout(5000)
        await pg.screenshot(path='u4_true.png')
        await pg.evaluate("__app.flyTo(__app.B.moon)")
        await pg.wait_for_timeout(4000)
        await pg.screenshot(path='u5_true_moon.png')
        await pg.click('[data-act="scale0"]')
        await pg.evaluate("__app.time.jd=2474000.5; __app.time.paused=true; __app.flyTo(__app.B.halley)")
        await pg.wait_for_timeout(4500)
        await pg.evaluate("__app.cam.goal*=6")
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path='u6_halley.png')
        print(await pg.evaluate("JSON.stringify([__app.B.halley.r, __app.B.mars.r, __app.store])"))
        print('\n'.join(logs[:20]))
        await b.close()
        b = await p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'])
        pg = await b.new_page(viewport={'width':390,'height':780})
        await pg.goto('http://localhost:8765/index.html')
        await pg.wait_for_timeout(5000)
        await pg.screenshot(path='m1.png')
        await pg.click('[data-start="kid"]')
        await pg.evaluate("__app.flyTo(__app.B.mars)")
        await pg.wait_for_timeout(4500)
        await pg.screenshot(path='m2.png')
        await pg.click('[data-act="card-close"]'); await pg.click('[data-tab="quiz"]'); await pg.click('[data-act="quiz-start"]'); await pg.click('[data-ans="1"]')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='m3.png')
        await b.close()
asyncio.run(main()); srv.terminate()
